def get_gate_keyboard() -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="«Відчиняй, бо молотом виб'ю!»", callback_data="gate:wrong1")],
        [InlineKeyboardButton(text="«Так потруси»", callback_data="gate:correct")],
        [InlineKeyboardButton(text="«Значить, погано струшуєш»", callback_data="gate:wrong2")],
    ])


def get_hub_keyboard(user_id: int) -> InlineKeyboardMarkup:
    u = get_user(user_id)
    buttons = []
    for q_id, q_data in QUESTS.items():
        done_mark = "✅ " if q_id in u["completed"] else ""
        buttons.append([InlineKeyboardButton(
            text=f"{done_mark}{q_data['title']}",
            callback_data=f"loc:{q_id}"
        )])

    buttons.append([InlineKeyboardButton(
        text=f"🎒 Мій інвентар ({len(u['items'])}) та Зачіпки ({u['info']})",
        callback_data="status"
    )])

    if len(u["completed"]) == len(QUESTS):
        buttons.append([InlineKeyboardButton(
            text="⚔️ Вирушити до лігва Відьми-швідьми!",
            callback_data="boss_intro"
        )])

    return InlineKeyboardMarkup(inline_keyboard=buttons)


def get_stage_keyboard(user_id: int, stage_num: int) -> InlineKeyboardMarkup:
    u = get_user(user_id)
    stage = BOSS_STAGES[stage_num]
    req_item = stage["req_item"]
    buttons = []

    if req_item in u["items"]:
        buttons.append([InlineKeyboardButton(
            text=stage["item_btn"],
            callback_data=f"boss_act:{stage_num}:item"
        )])

    buttons.append([InlineKeyboardButton(
        text=stage["direct_btn"],
        callback_data=f"boss_act:{stage_num}:direct"
    )])

    return InlineKeyboardMarkup(inline_keyboard=buttons)


def hp_bar(hp: int, max_hp: int) -> str:
    return "❤️️" * hp + "🖤" * max(0, max_hp - hp) + f" ({hp}/{max_hp})"

