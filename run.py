    option = QUESTS[q_id]["options"][opt_id]
    u["completed"].add(q_id)
    u["info"] += option["info_delta"]

    if option["item"]:
        item = option["item"]
        u["items"][item["id"]] = item

    kb = InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="🏘 Повернутися на площу", callback_data="hub")]
    ])
    await send_or_replace(call, text=option["result_text"], kb=kb)
    await call.answer()


